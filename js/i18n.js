function t(key) {
  const langVal = STRINGS[_lang] && STRINGS[_lang][key];
  if (langVal !== undefined) return langVal;
  const enVal = STRINGS['en'][key];
  if (enVal !== undefined) return enVal;
  return key;
}

function toggleLang() {
  setLang(_lang === 'en' ? 'es' : 'en');
}

function setLang(lang) {
  const prevLang = _lang;
  _lang = lang;
  localStorage.setItem('wod_lang', _lang);
  // Clear saved voice when language changes — it won't match new language voices
  if (prevLang !== lang) {
    localStorage.removeItem('wod-voice-name');
    populateVoiceSelector();
    saveProfile(); // persist the cleared voice to Supabase
  }
  applyLang();
}

function applyLang() {
  const langPicker = document.getElementById('lang-picker-val');
  if (langPicker) langPicker.textContent = _lang === 'en' ? '🇬🇧 English' : '🇪🇸 Español';
  // Update all elements with data-i18n attribute (textContent — safe, no HTML)
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  // Update all elements with data-i18n-html attribute (innerHTML — for strings with bold/em tags)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  // Update all elements with data-i18n-placeholder attribute
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  // Update dynamic content
  updateI18nDynamic();
}

// Apply translations to a dynamically created element and its children
function applyLangToEl(el) {
  if (!el) return;
  if (el.dataset?.i18n) el.textContent = t(el.dataset.i18n);
  if (el.dataset?.i18nHtml) el.innerHTML = t(el.dataset.i18nHtml);
  if (el.dataset?.i18nPlaceholder) el.placeholder = t(el.dataset.i18nPlaceholder);
  el.querySelectorAll?.('[data-i18n]').forEach(c => { c.textContent = t(c.dataset.i18n); });
  el.querySelectorAll?.('[data-i18n-html]').forEach(c => { c.innerHTML = t(c.dataset.i18nHtml); });
  el.querySelectorAll?.('[data-i18n-placeholder]').forEach(c => { c.placeholder = t(c.dataset.i18nPlaceholder); });
}

function updateI18nDynamic() {
  // Tab labels
  const tabs = [
    [0,'tab.profile'],[1,'tab.builder'],[2,'tab.timer'],
    [3,'tab.analytics'],[4,'tab.sessions'],[5,'tab.history']
  ];
  document.querySelectorAll('.tab-btn span').forEach((el,i) => {
    const key = tabs[i]?.[1];
    if (key) el.textContent = t(key);
  });
  // Profile tab labels
  const profileTabLabels = ['profile.tab.athlete','profile.tab.perf','profile.tab.custom'];
  document.querySelectorAll('.profile-tab').forEach((el,i) => {
    if (profileTabLabels[i]) el.textContent = t(profileTabLabels[i]);
  });
  // Reset button
  const resetBtn = document.getElementById('reset-btn');
  if (resetBtn) resetBtn.textContent = '⟳ ' + t('btn.reset');
  // Theme button — keep emoji, update label
  const themeBtn = document.getElementById('theme-btn');
  if (themeBtn) {
    const isDark = document.body.classList.contains('dark');
    themeBtn.textContent = isDark ? '☀️ ' + t('btn.light') : '🌙 ' + t('btn.dark');
  }
  // Refresh profile picker display values (gender, exp, goal)
  if (typeof refreshProfileDisplays === 'function') refreshProfileDisplays();
  if (typeof updateProfileStats === 'function') updateProfileStats();
  if (typeof updateGoalRec === 'function') updateGoalRec();
  if (typeof updateGoalRec === 'function') updateGoalRec();
  // Highlight active language button
  const btnEn = document.getElementById('lang-btn-en');
  const btnEs = document.getElementById('lang-btn-es');
  if (btnEn && btnEs) {
    btnEn.style.borderColor = _lang === 'en' ? 'var(--brand)' : 'var(--border)';
    btnEn.style.background  = _lang === 'en' ? 'var(--brand)' : 'var(--surface2)';
    btnEn.style.color       = _lang === 'en' ? 'white' : 'var(--text)';
    btnEs.style.borderColor = _lang === 'es' ? 'var(--brand)' : 'var(--border)';
    btnEs.style.background  = _lang === 'es' ? 'var(--brand)' : 'var(--surface2)';
    btnEs.style.color       = _lang === 'es' ? 'white' : 'var(--text)';
  }
  // Re-render dynamic screens to pick up new language
  if (typeof renderHistory === 'function') renderHistory();
  if (currentTab === 3 && typeof renderAnalytics === 'function') { renderAnalytics(); }
  // Re-apply data-i18n after dynamic renders (some renders regenerate DOM)
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  if (currentTab === 1 && typeof renderBlocks === 'function') renderBlocks();
  if (currentTab === 5 && typeof setHistView === 'function') setHistView(_histView);
  // Update cwod-select placeholder option text
  document.querySelectorAll('.cwod-select option[value=""]').forEach(opt => {
    opt.textContent = t('block.choose.wod');
  });
  // Re-render training load (uses t() internally, needs refresh on lang switch)
  if (typeof renderTrainingLoad === 'function') renderTrainingLoad();
  if (typeof updateBlueprint === 'function') updateBlueprint();
  // Re-render VO2max estimated display with correct language
  if (typeof updateVO2maxEstimate === 'function') updateVO2maxEstimate();
  // Re-render measurement status
  if (typeof loadMeasurements === 'function') loadMeasurements();
  // Re-render benchmark PRs empty state
  if (typeof rebuildBenchmarkPRs === 'function') rebuildBenchmarkPRs();
  // Update voice toggle label
  document.querySelectorAll('#voiceToggleLabel').forEach(el => {
    el.textContent = (typeof voiceEnabled !== 'undefined' && voiceEnabled) ? t('timer.voice.on') : t('timer.voice.off');
  });
  // Update READY label if timer not running
  const roundInfo = document.getElementById('roundInfo');
  if (roundInfo && roundInfo.textContent === 'READY') roundInfo.textContent = t('timer.ready');
  // Re-render profile highlights in current language
  const activeProfileTab = parseInt(localStorage.getItem('wod_profile_tab') || '0');
  if (typeof renderProfileHighlights === 'function') renderProfileHighlights(activeProfileTab);
}
